"""Read a completed refund file back in.

Expected: the bulk-payment file generated by refund_file.write_refund_file
(sheet "Mẫu file_File Template", data from row 4, columns A–G filled — the ref
is embedded at the end of the remark in column G as "… - <ref_no>") with two
status columns filled in by ops: Status in column P (16) and Reason in column
Q (17). Rows are matched back to refunds by that ref_no, falling back to
beneficiary account (C) + remark (G) if the ref can't be parsed.
"""
from __future__ import annotations

import openpyxl

from . import config


def parse_result_file(path: str) -> list[dict]:
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb[config.REFUND_SHEET] if config.REFUND_SHEET in wb.sheetnames else wb.active
    C = config.REFUND_COL
    results: list[dict] = []
    for row in ws.iter_rows(min_row=config.REFUND_DATA_START, values_only=True):
        def get(col_idx):  # 1-based column -> value or ""
            i = col_idx - 1
            return row[i] if i < len(row) and row[i] is not None else ""

        account = str(get(C["account"])).strip()
        remark = str(get(C["remark"])).strip()
        # Ref is the tail of the remark after the last " - " separator.
        ref_no = ""
        if config.REFUND_REF_SEP in remark:
            ref_no = remark.rsplit(config.REFUND_REF_SEP, 1)[1].strip()
        stt = get(C["stt"])
        if not account and not remark and not ref_no and not str(stt).strip():
            continue  # blank row
        results.append({
            "ref_no": ref_no,
            "beneficiary_account": account,
            "payment_detail": remark,
            "status": str(get(config.REFUND_STATUS_COL)).strip(),
            "reason": str(get(config.REFUND_REASON_COL)).strip() or None,
        })
    wb.close()
    return results
