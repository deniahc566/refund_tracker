"""Read a completed refund file back in.

Expected: the same file generated by refund_file.write_refund_file (headers on
row 2, data from row 3, Ref in column G) with two extra columns filled in by
ops: Status (col H) and Reason (col I). Rows are matched to refunds by Ref.
"""
from __future__ import annotations

import openpyxl

from . import config


def parse_result_file(path: str) -> list[dict]:
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb.active
    results: list[dict] = []
    for row in ws.iter_rows(min_row=config.REFUND_DATA_START, values_only=True):
        def get(col_idx):  # col_idx is 1-based
            i = col_idx - 1
            return row[i] if i < len(row) and row[i] is not None else ""

        ref_no = str(get(config.REFUND_REF_COL)).strip()
        stt = get(1)
        if not ref_no and not str(stt).strip():
            continue  # blank row
        results.append({
            "ref_no": ref_no,
            "status": str(get(config.REFUND_STATUS_COL)).strip(),
            "reason": str(get(config.REFUND_REASON_COL)).strip() or None,
        })
    wb.close()
    return results
